export function renderHtml(doc: ExportDocument): string {
  return [
    "<!doctype html>",
    '<html lang="en"><head><meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width,initial-scale=1">',
    // The export is static: forbid scripts and remote resources entirely.
    `<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'">`,
    `<title>${escapeHtml(doc.title)}</title><style>${STYLE}</style></head><body>`,
    `<h1>${escapeHtml(doc.title)}</h1><p class="sub">${escapeHtml(doc.subtitle)}</p>`,
    ...doc.blocks.map(htmlBlock),
    "<footer>Generated by RepoLens from deterministic static analysis. Security indicators are potential concerns, not confirmed vulnerabilities.</footer>",
    "</body></html>",
  ].join("\n");
}

// ---- Download -----------------------------------------------------------------------------

export type ExportFormat = "json" | "markdown" | "html";

export function exportReport(report: AnalysisReport, format: ExportFormat): { filename: string; mime: string; content: string } {
  const base = `repolens-${report.repository.full_name.replace("/", "-")}-${report.analysis.commit_sha.slice(0, 7)}`;
  if (format === "json") {
    return { filename: `${base}.json`, mime: "application/json", content: JSON.stringify(report, null, 2) };
  }
  const doc = buildExportDocument(report);
  if (format === "markdown") {
    return { filename: `${base}.md`, mime: "text/markdown", content: renderMarkdown(doc) };
  }
  return { filename: `${base}.html`, mime: "text/html", content: renderHtml(doc) };
}

export function downloadFile(filename: string, mime: string, content: string): void {
  const url = URL.createObjectURL(new Blob([content], { type: `${mime};charset=utf-8` }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
