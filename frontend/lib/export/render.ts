import type { AnalysisReport } from "../api/types";
import { buildExportDocument, type Block, type ExportDocument } from "./document";

// ---- Markdown ----------------------------------------------------------------------------

/** Escape text so repository-derived content cannot inject Markdown/HTML structure. */
export function escapeMarkdown(text: string): string {
  return text
    .replace(/\r?\n/g, " ")
    .replace(/([\\`*_{}[\]<>|#])/g, "\\$1");
}

function mdBlock(block: Block): string {
  switch (block.kind) {
    case "heading":
      return `${"#".repeat(block.level)} ${escapeMarkdown(block.text)}`;
    case "paragraph":
      return escapeMarkdown(block.text);
    case "note":
      return `> ${escapeMarkdown(block.text)}`;
    case "list":
      return block.items.map((i) => `- ${escapeMarkdown(i)}`).join("\n");
    case "table": {
      const align = block.headers.map((_, i) => (block.align?.[i] === "right" ? "---:" : "---"));
      const row = (cells: string[]) => `| ${cells.map((c) => escapeMarkdown(c) || " ").join(" | ")} |`;
      return [row(block.headers), `| ${align.join(" | ")} |`, ...block.rows.map(row)].join("\n");
    }
  }
}

export function renderMarkdown(doc: ExportDocument): string {
  return [`# ${escapeMarkdown(doc.title)}`, `_${escapeMarkdown(doc.subtitle)}_`, ...doc.blocks.map(mdBlock)].join("\n\n") + "\n";
}

// ---- HTML ----------------------------------------------------------------------------------

export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function htmlBlock(block: Block): string {
  switch (block.kind) {
    case "heading":
      return `<h${block.level}>${escapeHtml(block.text)}</h${block.level}>`;
    case "paragraph":
      return `<p>${escapeHtml(block.text)}</p>`;
    case "note":
      return `<p class="note">${escapeHtml(block.text)}</p>`;
    case "list":
      return `<ul>${block.items.map((i) => `<li>${escapeHtml(i)}</li>`).join("")}</ul>`;
    case "table": {
      const cls = (i: number) => (block.align?.[i] === "right" ? ' class="num"' : "");
      const head = block.headers.map((h, i) => `<th${cls(i)}>${escapeHtml(h)}</th>`).join("");
      const body = block.rows
        .map((r) => `<tr>${r.map((c, i) => `<td${cls(i)}>${escapeHtml(c)}</td>`).join("")}</tr>`)
        .join("");
      return `<table><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>`;
    }
  }
}

